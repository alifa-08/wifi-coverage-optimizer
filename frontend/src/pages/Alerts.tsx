import React, { useState } from 'react';
import { Bell, CheckCircle, AlertTriangle, ShieldAlert, Filter, Clock } from 'lucide-react';
import { Alert } from '../types';
import { SeverityBadge } from '../components/SeverityBadge';

interface AlertsProps {
  alerts: Alert[];
  onResolveAlert: (alertId: number) => void;
}

export const Alerts: React.FC<AlertsProps> = ({ alerts, onResolveAlert }) => {
  const [filterStatus, setFilterStatus] = useState<'ALL' | 'ACTIVE' | 'RESOLVED'>('ALL');

  const filtered = alerts.filter((a) => {
    if (filterStatus === 'ALL') return true;
    return a.status === filterStatus;
  });

  const activeCount = alerts.filter((a) => a.status === 'ACTIVE').length;

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 p-5 rounded-2xl bg-slate-900 border border-slate-800">
        <div>
          <div className="flex items-center space-x-2 text-rose-400 font-bold text-xs uppercase tracking-wider mb-1">
            <Bell className="w-4 h-4" />
            <span>Operational Alert Center</span>
          </div>
          <h2 className="text-xl font-extrabold text-white tracking-tight">
            Network Dead-Zone Incident Feed
          </h2>
          <p className="text-xs text-slate-400 max-w-2xl mt-1">
            Real-time automated incident triggers generated by severe or persistent dead-zone detection events.
          </p>
        </div>

        {/* Filter Controls */}
        <div className="flex items-center space-x-1 bg-slate-950 p-1 rounded-xl border border-slate-800 text-xs">
          <button
            onClick={() => setFilterStatus('ALL')}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all ${
              filterStatus === 'ALL' ? 'bg-indigo-600 text-white' : 'text-slate-400 hover:text-white'
            }`}
          >
            All ({alerts.length})
          </button>
          <button
            onClick={() => setFilterStatus('ACTIVE')}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all ${
              filterStatus === 'ACTIVE' ? 'bg-rose-600 text-white' : 'text-slate-400 hover:text-white'
            }`}
          >
            Active ({activeCount})
          </button>
          <button
            onClick={() => setFilterStatus('RESOLVED')}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all ${
              filterStatus === 'RESOLVED' ? 'bg-emerald-600 text-white' : 'text-slate-400 hover:text-white'
            }`}
          >
            Resolved ({alerts.length - activeCount})
          </button>
        </div>
      </div>

      {/* Alerts Feed */}
      <div className="space-y-3">
        {filtered.map((alert) => (
          <div
            key={alert.id}
            className={`p-4 rounded-xl border transition-all shadow-md ${
              alert.status === 'ACTIVE'
                ? 'bg-slate-900 border-slate-800 hover:border-slate-700'
                : 'bg-slate-950/60 border-slate-900 opacity-70'
            }`}
          >
            <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-3">
              <div className="space-y-1">
                <div className="flex items-center gap-2">
                  <SeverityBadge severity={alert.severity} />
                  <span className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                    {alert.alert_type.replace(/_/g, ' ')}
                  </span>
                  <span className="text-[11px] text-slate-400 flex items-center gap-1">
                    <Clock className="w-3 h-3" />
                    {new Date(alert.created_at).toLocaleTimeString()}
                  </span>
                </div>
                <h4 className="text-sm font-bold text-slate-100">{alert.title}</h4>
                <p className="text-xs text-slate-300 leading-relaxed max-w-3xl">
                  {alert.message}
                </p>
                {alert.location_x !== null && alert.location_y !== null && (
                  <p className="text-[11px] text-slate-400 font-mono">
                    Incident Coordinate: ({alert.location_x}m, {alert.location_y}m)
                  </p>
                )}
              </div>

              {/* Status & Resolve Button */}
              <div className="flex items-center gap-3 shrink-0">
                {alert.status === 'ACTIVE' ? (
                  <button
                    onClick={() => onResolveAlert(alert.id)}
                    className="flex items-center space-x-1.5 px-3 py-1.5 rounded-lg bg-emerald-600/10 border border-emerald-500/30 hover:bg-emerald-600/20 text-emerald-400 font-semibold text-xs transition-all cursor-pointer"
                  >
                    <CheckCircle className="w-3.5 h-3.5" />
                    <span>Resolve Incident</span>
                  </button>
                ) : (
                  <span className="px-2.5 py-1 rounded-md bg-emerald-500/10 text-emerald-400 border border-emerald-500/20 text-xs font-semibold">
                    Resolved
                  </span>
                )}
              </div>
            </div>
          </div>
        ))}

        {filtered.length === 0 && (
          <div className="p-12 text-center text-xs text-slate-400 bg-slate-900 border border-slate-800 rounded-xl">
            No alerts found matching filter.
          </div>
        )}
      </div>
    </div>
  );
};
